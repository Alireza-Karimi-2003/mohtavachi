def build_prompt(
    profile: dict,
    kind: str,
    request: str,
    length: str = "medium",
    variant_count: int = 2,
) -> str:
    niche = profile.get("niche") or "نامشخص"
    audience = profile.get("audience") or "نامشخص"
    tone = profile.get("tone") or "نامشخص"
    main_offer = profile.get("main_offer") or "نامشخص"
    differentiator = profile.get("differentiator") or "نامشخص"
    content_goal = profile.get("content_goal") or "نامشخص"
    plan = profile.get("plan") or "free"

    variant_count = max(1, min(variant_count, 2))

    return f"""
پروفایل برند:
- حوزه: {niche}
- مخاطب: {audience}
- لحن: {tone}
- محصول/خدمت اصلی: {main_offer}
- مزیت/تفاوت برند: {differentiator}
- هدف اصلی محتوا: {content_goal}
- پلن: {plan}

نوع محتوا: {kind}
تعداد خروجی: {variant_count}
سطح طول: {LENGTHS.get(length, LENGTHS["medium"])}

دستور این نوع محتوا:
{INSTRUCTIONS.get(kind, INSTRUCTIONS["caption"])}

سقف خروجی: حداکثر {OUTPUT_LIMITS.get(kind, 1800)} کاراکتر. اگر لازم شد، جزئیات کم‌اهمیت را حذف کن و به سقف پایبند بمان.

درخواست/اطلاعات کاربر:
{request}

اکنون فقط خروجی نهایی را طبق دستور بالا تولید کن.
""".strip()


async def generate(
    profile: dict,
    kind: str,
    request: str,
    length: str = "medium",
    variant_count: int = 2,
    model_override: str | None = None,
) -> str:
    input_limit = {
        "caption": 1200, "post": 1600, "story": 1600, "reel": 1800,
        "product": 1200, "ideas": 1600, "rewrite": 3000, "brief": 1800,
        "pack": 2200, "campaign": 2200, "daily_suggestion": 1200,
    }.get(kind, 1800)
    if len(request) > input_limit:
        raise ValueError(f"ورودی این ابزار بیش از حد طولانی است (حداکثر {input_limit} کاراکتر).")

    prompt = build_prompt(profile, kind, request, length, variant_count)

    if settings.ai_provider == "ollama":
        url = f"{settings.ollama_base_url.rstrip('/')}/api/chat"
        payload = {
            "model": model_override or settings.ollama_model,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
            "stream": False,
            "think": False,
            "keep_alive": "10m",
            "options": {
                "temperature": 0.4,
                "num_ctx": 4096,
                "num_predict": 3200 if kind == "pack" else 1800,
            },
        }

        async with httpx.AsyncClient(timeout=settings.ollama_timeout) as client:
            r = await client.post(url, json=payload)
            r.raise_for_status()
            data = r.json()
            output = data["message"]["content"].strip()
            max_output = OUTPUT_LIMITS.get(kind, 1800)
            if len(output) > max_output:
                cut = output[:max_output]
                boundary = max(cut.rfind("\n\n"), cut.rfind("\n"), cut.rfind("."), cut.rfind("؟"), cut.rfind("!"))
                if boundary >= int(max_output * 0.75):
                    cut = cut[:boundary].rstrip()
                output = cut.rstrip() + "…"
            return output

    if settings.ai_provider == "openai_compatible":
        if not settings.ai_api_base_url or not settings.ai_model:
            raise RuntimeError("AI_API_BASE_URL و AI_MODEL تنظیم نشده‌اند.")

        headers = {"Content-Type": "application/json"}
        if settings.ai_api_key:
            headers["Authorization"] = f"Bearer {settings.ai_api_key}"

        async def call_model(model: str, reasoning_effort: str | None = None) -> str:
            payload = {
                "model": model,
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": prompt},
                ],
                "temperature": 1.0,
                "max_tokens": MAX_TOKENS.get(kind, 1200),
            }
            if reasoning_effort:
                payload["reasoning_effort"] = reasoning_effort
            async with httpx.AsyncClient(timeout=settings.ollama_timeout) as client:
                r = await client.post(
                    f"{settings.ai_api_base_url.rstrip('/')}/chat/completions",
                    json=payload,
                    headers=headers,
                )
                r.raise_for_status()
                return r.json()["choices"][0]["message"]["content"].strip()

        try:
            primary_model = model_override or settings.ai_model
            if not primary_model:
                raise RuntimeError("AI_MODEL تنظیم نشده است.")
            output = await call_model(primary_model)
        except Exception as primary_exc:
            fallback = settings.ai_fallback_model.strip()
            if model_override:
                raise
            if not fallback or fallback == settings.ai_model:
                raise
            print(f"Primary AI failed ({type(primary_exc).__name__}); trying fallback model {fallback}.")
            output = await call_model(fallback, settings.ai_fallback_reasoning_effort or None)

        max_output = OUTPUT_LIMITS.get(kind, 1800)
        if len(output) > max_output:
            cut = output[:max_output]
            boundary = max(cut.rfind("\n\n"), cut.rfind("\n"), cut.rfind("."), cut.rfind("؟"), cut.rfind("!"))
            if boundary >= int(max_output * 0.75):
                cut = cut[:boundary].rstrip()
            output = cut.rstrip() + "…"
        return output


    raise RuntimeError(f"AI_PROVIDER ناشناخته است: {settings.ai_provider}")


async def generate_image(profile: dict, request: str, model_override: str | None = None) -> bytes:
    if not settings.ai_api_base_url or not settings.ai_api_key:
        raise RuntimeError("تنظیمات API تصویر کامل نیست.")
    import base64
    import json
    prompt = (
        f"حوزه برند: {profile.get('niche') or 'نامشخص'}\n"
        f"مخاطب: {profile.get('audience') or 'نامشخص'}\n"
        f"لحن/هویت بصری: {profile.get('tone') or 'نامشخص'}\n"
        f"محصول/خدمت اصلی: {profile.get('main_offer') or 'نامشخص'}\n"
        f"مزیت/تفاوت برند: {profile.get('differentiator') or 'نامشخص'}\n"
        f"هدف اصلی محتوا: {profile.get('content_goal') or 'نامشخص'}\n\n"
        f"درخواست تصویر کاربر: {request}\n\n"
        "تصویر حرفه‌ای و مناسب محتوای شبکه‌های اجتماعی تولید کن. "
        "اطلاعاتی که کاربر نداده را درباره محصول یا برند اختراع نکن."
    )
    payload = {
        "model": model_override or settings.ai_image_model,
        "prompt": prompt,
        "size": "1024x1024",
        "quality": "medium",
        "n": 1,
    }
    headers = {"Content-Type": "application/json", "Authorization": f"Bearer {settings.ai_api_key}"}
    async with httpx.AsyncClient(timeout=settings.ollama_timeout) as client:
        r = await client.post(f"{settings.ai_api_base_url.rstrip('/')}/images/generations", json=payload, headers=headers)
        r.raise_for_status()
        data = r.json()
    item = data.get("data", [{}])[0]
    if item.get("b64_json"):
        return base64.b64decode(item["b64_json"])
    url = item.get("url")
    if not url:
        raise RuntimeError("API تصویر خروجی قابل دریافت برنگرداند.")
    async with httpx.AsyncClient(timeout=60) as client:
        img = await client.get(url)
        img.raise_for_status()
        return img.content
